"""Daily Brief foundation (Personal Executive AI Assistant pivot, Phase 10).

Extracted from api/routers/brief.py's GET /api/brief — same behavior,
now organized as an explicit service instead of logic inline in the
router. Reuses summaries/actions already produced by the Fast-Track
pipeline (no new generation, per the pivot plan: "reuse existing
summaries").

"DailySummaryGenerator"/"PriorityDetector" (named in the pivot plan) are
kept as methods here rather than separate classes — same reasoning as
Memory/Knowledge (Units 46-47): a couple of lines each, splitting them now
would be premature abstraction. "Priority detection" is what
_upcoming_deadline_count/_pending_actions_summary/at_risk_projects
already do: pick which pending actions/deadlines surface as
recommended_actions. There is no separate "generator" step because this
service does not generate new summaries — it reads ProjectSummary.content,
already generated by the Fast-Track.
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from typing import List, Optional, Tuple

from sqlalchemy.orm import Session

from email_analyzer.db.models import Project, SuggestedAction
from email_analyzer.repositories.brief_repository import BriefRepository

# Fenêtre "échéances cette semaine" (jours) et de repli pour un tout premier
# login (previous_login_at absent — pas de session antérieure à comparer).
UPCOMING_DEADLINE_DAYS = 7
FIRST_VISIT_FALLBACK_DAYS = 7
RECOMMENDED_ACTIONS_LIMIT = 5


@dataclass
class BriefCounts:
    new_projects: int
    pending_actions: int
    upcoming_deadlines: int
    important_emails: int
    at_risk_projects: int


@dataclass
class DailyBrief:
    since: Optional[datetime]
    counts: BriefCounts
    recommended_actions: List[Tuple[SuggestedAction, Project]]


class BriefService:
    def __init__(self, db: Session) -> None:
        self._repo = BriefRepository(db)

    def build_daily_brief(self, tenant_id: uuid.UUID, previous_login_at: Optional[datetime]) -> DailyBrief:
        since = previous_login_at or (
            datetime.now(timezone.utc) - timedelta(days=FIRST_VISIT_FALLBACK_DAYS)
        )

        pending_actions_rows = self._repo.list_pending_actions_with_project(tenant_id)

        return DailyBrief(
            since=previous_login_at,
            counts=BriefCounts(
                new_projects=self._repo.count_new_projects(tenant_id, since),
                pending_actions=len(pending_actions_rows),
                upcoming_deadlines=self._upcoming_deadline_count(pending_actions_rows),
                important_emails=self._repo.count_important_emails(tenant_id, since),
                at_risk_projects=self._repo.count_at_risk_projects(tenant_id),
            ),
            recommended_actions=pending_actions_rows[:RECOMMENDED_ACTIONS_LIMIT],
        )

    def _upcoming_deadline_count(
        self, pending_actions_rows: List[Tuple[SuggestedAction, Project]]
    ) -> int:
        """"Priority detection" v1 : une action est prioritaire si son
        échéance tombe dans les UPCOMING_DEADLINE_DAYS prochains jours."""
        cutoff = datetime.now(timezone.utc) + timedelta(days=UPCOMING_DEADLINE_DAYS)
        return sum(
            1
            for action, _ in pending_actions_rows
            if action.deadline is not None and action.deadline <= cutoff
        )
